// Embed the painted VN artwork (assets/vn/<id>.webp) as data URLs so the
// single-file build stays self-contained. Usage: node tools/build-vn-art.js
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'vn');
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.webp')).sort()) {
  out[path.basename(f, '.webp')] = 'data:image/webp;base64,' + fs.readFileSync(path.join(dir, f)).toString('base64');
}
const js = '// Generated by tools/build-vn-art.js; replace assets/vn/*.webp and rerun instead.\nwindow.VN_ART_DATA = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'vn-art-data.js'), js);
console.log('vn art:', Object.keys(out).join(', '), (js.length / 1024).toFixed(1) + ' KB');
